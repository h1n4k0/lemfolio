"""Generate Python/Pydantic and TypeScript DTOs from the same versioned schema."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def generate(check=False):
    source = ROOT / 'contracts/v1/schema.json'
    raw = source.read_text(encoding='utf-8')
    schema = json.loads(raw)
    definitions = schema['$defs']
    def typ(node, language):
        if '$ref' in node:
            return node['$ref'].rsplit('/', 1)[1]
        if 'const' in node or 'enum' in node:
            values = [node['const']] if 'const' in node else node['enum']
            return ('Literal[' + ', '.join(repr(v) for v in values) + ']') if language == 'py' else ' | '.join(json.dumps(v) for v in values)
        if 'anyOf' in node:
            return ' | '.join(typ(item, language) for item in node['anyOf'])
        kind = node.get('type', 'object')
        if kind == 'array':
            item = typ(node['items'], language)
            return f'list[{item}]' if language == 'py' else f'Array<{item}>'
        if kind == 'object':
            value = node.get('additionalProperties', True)
            mapped = typ(value, language) if isinstance(value, dict) else ('Any' if language == 'py' else 'unknown')
            return f'dict[str, {mapped}]' if language == 'py' else f'Record<string, {mapped}>'
        return {'string':('str','string'),'integer':('int','number'),'number':('float','number'),'boolean':('bool','boolean'),'null':('None','null')}[kind][language == 'ts']
    def predicate(rule, target='value'):
        terms=[f'{key!r} in {target}' for key in rule.get('required',[])]
        for key, condition in rule.get('properties',{}).items():
            if not condition:
                continue
            member=f'{target}[{key!r}]';tests=[]
            if condition.get('type')=='null':tests.append(f'{member} is None')
            elif condition.get('type')=='array':
                tests.append(f'isinstance({member},list)')
                if 'minItems' in condition:tests.append(f'len({member}) >= {condition["minItems"]}')
            else:raise ValueError('Unsupported conditional schema type; extend the generator explicitly')
            terms.append(f'({key!r} not in {target} or ('+' and '.join(tests)+'))')
        return '('+' and '.join(terms or ['True'])+')'
    # Hash the LF form stored in Git so the digest does not depend on checkout line endings.
    digest = hashlib.sha256(source.read_bytes().replace(bytes([13, 10]), bytes([10]))).hexdigest()
    py = ['# Generated by scripts/generate_contracts.py; edit contracts/v1/schema.json.', 'from __future__ import annotations', 'from typing import Any, Literal', 'from pydantic import BaseModel, ConfigDict, Field, model_validator', '', f'CONTRACT_VERSION = {schema["contract_version"]!r}', f'CONTRACT_SCHEMA_SHA256 = {digest!r}', '']
    ts = ['// Generated by scripts/generate_contracts.py; edit contracts/v1/schema.json.', f'export const CONTRACT_VERSION = {schema["contract_version"]!r} as const;', '']
    for name, node in definitions.items():
        py.extend([f'class {name}(BaseModel):', '    model_config = ConfigDict(strict=True, extra=' + repr('allow' if node.get('additionalProperties') else 'forbid') + ')'])
        ts.append(f'export interface {name} {{')
        required = node.get('required', [])
        for field, value in node['properties'].items():
            annotation = typ(value, 'py')
            optional = field not in required
            default = value.get('default')
            if optional and default is None and 'None' not in annotation:
                annotation += ' | None'
            constraints = []
            for key, param in [('minLength','min_length'),('maxLength','max_length'),('minItems','min_length'),('maxItems','max_length'),('minimum','ge'),('maximum','le'),('pattern','pattern')]:
                if key in value:
                    constraints.append(f'{param}={value[key]!r}')
            if optional:
                if isinstance(default, (list, dict)):
                    constraints.insert(0, 'default_factory=' + ('list' if isinstance(default, list) else 'dict'))
                else:
                    constraints.insert(0, f'default={default!r}')
            assignment = ' = Field(' + ', '.join(constraints) + ')' if constraints else ''
            py.append(f'    {field}: {annotation}{assignment}')
            ts.append('  ' + json.dumps(field) + ('?' if optional else '') + ': ' + typ(value, 'ts') + ';')
        if 'oneOf' in node:
            choices=', '.join(predicate(rule) for rule in node['oneOf'])
            py.extend(['',"    @model_validator(mode='before')",'    @classmethod','    def validate_alternatives(cls,value):',f'        if isinstance(value,dict) and sum(({choices})) != 1:',"            raise ValueError('Exactly one explicit change operation is required')",'        return value'])
        py.append('')
        if node.get('additionalProperties'):
            ts.append('  [key: string]: unknown;')
        ts.extend(['}', ''])
    py.extend([f'{name}.model_rebuild()' for name in definitions])
    outputs = {ROOT/'src/lemfolio/_generated_contracts.py': '\n'.join(py)+'\n', ROOT/'frontend/generated/contracts.ts':'\n'.join(ts).rstrip()+'\n', ROOT/'frontend/generated/schema.json':raw}
    for path, content in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Generated contract drift: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    print('Contract generation check passed' if check else 'Contract DTOs generated')

if __name__ == '__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); generate(parser.parse_args().check)
