// Compile the canonical protocol at build time. Browser CSP remains script-src
// 'self': the delivered application never compiles schemas with new Function.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const root = new URL('../', import.meta.url);
const raw = await readFile(new URL('contracts/v1/schema.json', root), 'utf8');
const schema = JSON.parse(raw);
const names = Object.keys(schema.$defs).sort();
if (names.some(name => !/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name))) throw new Error('Contract DTO names must be valid JS exports');
const ajv = new Ajv2020({allErrors: true, strict: true, code: {source: true, esm: true, lines: true}});
ajv.addKeyword({keyword: 'contract_version', valid: true});
ajv.addSchema(schema);
const refs = Object.fromEntries(names.map(name => [name, `${schema.$id}#/$defs/${name}`]));
const source = standaloneCode(ajv, refs);
// Ajv's small string-length helper is a static CommonJS runtime dependency.
// Bundle that helper now so validators.js itself is browser-safe ESM.
const result = await build({stdin: {contents: source, resolveDir: fileURLToPath(root), sourcefile: 'standalone-validators.js'}, bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2022', legalComments: 'inline'});
// Hash the LF form stored in Git so the digest does not depend on checkout line endings.
const digest = createHash('sha256').update(raw.replaceAll('\r\n', '\n')).digest('hex');
const header = `// Generated by scripts/generate_validators.mjs from contracts/v1/schema.json.\n// Schema SHA-256: ${digest}\n`;
const declarations = `import type { ErrorObject } from 'ajv';\ninterface Validator { (data: unknown): boolean; errors?: ErrorObject[] | null }\n${names.map(name => `export const ${name}: Validator;`).join('\n')}\n`;
const outputs = new Map([
  ['frontend/generated/validators.js', header + result.outputFiles[0].text],
  ['frontend/generated/validators.d.ts', header + declarations],
]);
const check = process.argv.includes('--check');
for (const [name, value] of outputs) {
  const target = new URL(name, root);
  if (check) {
    const existing = await readFile(target, 'utf8').catch(() => '');
    if (existing !== value) throw new Error(`${name} is stale; run node scripts/generate_validators.mjs`);
  } else await writeFile(target, value, 'utf8');
}
console.log(check ? 'Standalone validators are current' : 'Generated CSP-safe standalone validators');
